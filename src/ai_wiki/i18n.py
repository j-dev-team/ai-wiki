def default_lang() -> str:
    from ai_wiki.language import wiki_language

    return wiki_language()


def translate(lang: str, key: str, **kwargs: object) -> str:
    active_lang = lang if lang in SUPPORTED_LANGS else default_lang()
    text = (UI_TRANSLATIONS.get(active_lang, {}).get(key)
            or TRANSLATIONS.get(active_lang, {}).get(key)
            or UI_TRANSLATIONS["en"].get(key)
            or TRANSLATIONS["en"].get(key) or key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text


def display_label(value: object, lang: str = "ko") -> str:
    text = str(value)
    if lang == "ko":
        return KOREAN_LABELS.get(text, text.replace("_", " "))
    return text.replace("_", " ").title()


def display_value(value: object, lang: str = "ko") -> str:
    text = str(value)
    if lang != "ko":
        return text
    if text in KOREAN_LABELS:
        return KOREAN_LABELS[text]
    for source, target in EASY_TERM_REPLACEMENTS:
        text = text.replace(source, target)
    return text
