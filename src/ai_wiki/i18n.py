def default_lang() -> str:
    lang = os.environ.get("AI_WIKI_LANG", "ko").lower()
    return lang if lang in SUPPORTED_LANGS else "ko"


def translate(lang: str, key: str, **kwargs: object) -> str:
    active_lang = lang if lang in SUPPORTED_LANGS else default_lang()
    text = TRANSLATIONS.get(active_lang, {}).get(key) or TRANSLATIONS["en"].get(key) or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text
